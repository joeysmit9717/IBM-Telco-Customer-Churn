CREATE TABLE customers (
    "CustomerID"         VARCHAR PRIMARY KEY,
    "Count"              INTEGER NOT NULL,
    "Country"            VARCHAR NOT NULL,
    "State"              VARCHAR NOT NULL,
    "City"               VARCHAR NOT NULL,
    "Zip Code"           INTEGER NOT NULL,
    "Lat Long"           VARCHAR NOT NULL,
    "Latitude"           DOUBLE PRECISION NOT NULL,
    "Longitude"          DOUBLE PRECISION NOT NULL,
    "Gender"             VARCHAR NOT NULL,
    "Senior Citizen"     VARCHAR NOT NULL,
    "Partner"            VARCHAR NOT NULL,
    "Dependents"         VARCHAR NOT NULL,
    "Tenure Months"      INTEGER NOT NULL,
    "Phone Service"      VARCHAR NOT NULL,
    "Multiple Lines"     VARCHAR NOT NULL,
    "Internet Service"   VARCHAR NOT NULL,
    "Online Security"    VARCHAR NOT NULL,
    "Online Backup"      VARCHAR NOT NULL,
    "Device Protection"  VARCHAR NOT NULL,
    "Tech Support"       VARCHAR NOT NULL,
    "Streaming TV"       VARCHAR NOT NULL,
    "Streaming Movies"   VARCHAR NOT NULL,
    "Contract"           VARCHAR NOT NULL,
    "Paperless Billing"  VARCHAR NOT NULL,
    "Payment Method"     VARCHAR NOT NULL,
    "Monthly Charges"    NUMERIC(8,2) NOT NULL,
    "Total Charges"      VARCHAR,
    "Churn Label"        VARCHAR NOT NULL,
    "Churn Value"        INTEGER NOT NULL,
    "Churn Score"        INTEGER NOT NULL,
    "CLTV"               INTEGER NOT NULL,
    "Churn Reason"       VARCHAR
);